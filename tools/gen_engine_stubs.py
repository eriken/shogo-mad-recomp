#!/usr/bin/env python3
"""Generate logging stub implementations of the LithTech engine interfaces
(ClientDE, ServerDE and their CSBase base) from Clang's AST of the real headers.

Every function-pointer field and every virtual method gets a stub that records
the call and returns a zero value. Real engine code later replaces stubs one by one.

Usage: gen_engine_stubs.py OUT.cpp AST_JSON...
  Each AST_JSON is the output of
  clang++ -Xclang -ast-dump=json -Xclang -ast-dump-filter -Xclang <Record> ...
"""
import json, re, sys

def load_objects(path):
    text = open(path).read()
    dec, i, out = json.JSONDecoder(), 0, []
    while i < len(text):
        while i < len(text) and text[i].isspace():
            i += 1
        if i >= len(text):
            break
        obj, i = dec.raw_decode(text, i)
        out.append(obj)
    return out

def find_records(objs, names):
    found = {}
    def walk(n):
        if isinstance(n, dict):
            if n.get('kind') == 'CXXRecordDecl' and n.get('name') in names and n.get('completeDefinition'):
                found[n['name']] = n
                return
            for c in n.get('inner', []):
                walk(c)
    for o in objs:
        walk(o)
    return found

FNPTR = re.compile(r'\(\*\)\s*\(')

def members(record):
    fields, methods = [], []
    for c in record.get('inner', []):
        k = c.get('kind')
        if k == 'FieldDecl':
            t = c['type'].get('desugaredQualType', c['type']['qualType'])
            if FNPTR.search(t) or FNPTR.search(c['type']['qualType']):
                fields.append(c['name'])
        elif k == 'CXXMethodDecl' and c.get('virtual'):
            qt = c['type']['qualType']
            ret = qt[:qt.index('(')].strip()
            params = [p['type']['qualType'] for p in c.get('inner', []) if p.get('kind') == 'ParmVarDecl']
            methods.append({
                'name': c['name'], 'ret': ret, 'params': params,
                'const': qt.rstrip().endswith('const'),
                'variadic': c.get('variadic', False) or qt.rstrip().endswith('...)'),
                'pure': c.get('pure', False),
                # Has a body in the header already (defined inline).
                'inline': any(x.get('kind') == 'CompoundStmt' for x in c.get('inner', [])),
            })
    return fields, methods

# Virtual methods can be replaced at runtime through a hook table indexed by
# "Iface::Method" (see shogo_set_virtual_hook). Variadic ones can't forward, so
# they stay stubs.
VHOOKS = []

def vhook_index(key):
    if key not in VHOOKS:
        VHOOKS.append(key)
    return VHOOKS.index(key)

def method_override(iface, m):
    args = ', '.join(f'shogo_stub::T_<{t}> a{i}' for i, t in enumerate(m['params']))
    if m['variadic']:
        args = (args + ', ...') if args else '...'
    const = ' const' if m['const'] else ''
    key = f'{iface}::{m["name"]}'
    hook = ''
    if not m['variadic']:
        idx = vhook_index(key)
        ptypes = ''.join(f', shogo_stub::T_<{t}>' for t in m['params'])
        fwd = ''.join(f', a{i}' for i in range(len(m['params'])))
        hook = (f'if (void *h = shogo_stub::g_vhooks[{idx}]) return reinterpret_cast<shogo_stub::T_<{m["ret"]}> (*)(void *{ptypes})>(h)'
                f'((void *)this{fwd}); ')
    return (f'    shogo_stub::T_<{m["ret"]}> {m["name"]}({args}){const} override\n'
            f'    {{ {hook}SHOGO_STUB_CALLED("{key}"); return shogo_stub::zero<{m["ret"]}>(); }}\n')

def main():
    out_path, ast_paths = sys.argv[1], sys.argv[2:]
    objs = [o for p in ast_paths for o in load_objects(p)]
    recs = find_records(objs, {'ClientDE', 'ServerDE', 'CSBase'})
    missing = {'ClientDE', 'ServerDE', 'CSBase'} - recs.keys()
    if missing:
        sys.exit(f'records not found in AST: {missing}')

    _, base_methods = members(recs['CSBase'])
    lines = ['// GENERATED by tools/gen_engine_stubs.py from the LithTech API headers. Do not edit.',
             '#include "engine/stub_support.h"', '#include <cstring>', '']
    names, counts = [], {}
    for iface in ('ClientDE', 'ServerDE'):
        fields, methods = members(recs[iface])
        # Pure virtuals of CSBase plus all of its non-pure virtuals: the original
        # engine supplied their bodies, so the stub engine must too.
        own = {(m['name'], tuple(m['params'])) for m in methods}
        inherited = [m for m in base_methods if (m['name'], tuple(m['params'])) not in own]
        cls = f'Stub{iface}'
        lines.append(f'class {cls} : public {iface}\n{{\npublic:')
        lines.append(f'    {cls}() {{ InstallFunctionTable(); }}')
        for m in inherited:
            lines.append(method_override('CSBase', m).rstrip('\n'))
        for m in methods:
            if m['name'].startswith('~'):
                continue
            lines.append(method_override(iface, m).rstrip('\n'))
        lines.append('\n    void InstallFunctionTable()\n    {')
        for f in fields:
            idx = len(names)
            names.append(f'{iface}::{f}')
            lines.append(f'        {f} = shogo_stub::Fn<decltype({f}), {idx}>::call;')
        lines.append('    }\n};\n')
        counts[iface] = (len(fields), len(methods), len(inherited))

    name_table = ['namespace shogo_stub {', 'const char *const kFunctionNames[] = {']
    name_table += [f'    "{n}",' for n in names]
    name_table += ['};', f'const int kFunctionCount = {len(names)};']
    name_table += ['const char *const kVirtualNames[] = {'] + [f'    "{n}",' for n in VHOOKS] + ['};']
    name_table += [f'const int kVirtualCount = {len(VHOOKS)};', f'void *g_vhooks[{max(1, len(VHOOKS))}];', '}', '']
    # The name table must precede the classes that reference it.
    lines[3:3] = name_table
    # Out-of-line bodies for non-pure virtuals declared in the API classes
    # (the original engine binary supplied these).
    for iface in ('CSBase', 'ClientDE', 'ServerDE'):
        _, methods = members(recs[iface])
        for m in methods:
            if m.get('pure') or m['name'].startswith('~') or m['inline']:
                continue
            args = ', '.join(f'shogo_stub::T_<{t}> a{i}' for i, t in enumerate(m['params']))
            if m['variadic']:
                args = (args + ', ...') if args else '...'
            const = ' const' if m['const'] else ''
            lines.append(f'shogo_stub::T_<{m["ret"]}> {iface}::{m["name"]}({args}){const}\n'
                         f'{{ SHOGO_STUB_CALLED("{iface}::{m["name"]}"); return shogo_stub::zero<{m["ret"]}>(); }}')
    lines.append('')
    lines.append('bool shogo_set_virtual_hook(const char *name, void *fn)\n{\n'
                 '    for (int i = 0; i < shogo_stub::kVirtualCount; ++i)\n'
                 '        if (!strcmp(shogo_stub::kVirtualNames[i], name)) { shogo_stub::g_vhooks[i] = fn; return true; }\n'
                 '    return false;\n}')
    lines.append('ClientDE *shogo_create_stub_client() { return new StubClientDE; }')
    lines.append('ServerDE *shogo_create_stub_server() { return new StubServerDE; }')
    open(out_path, 'w').write('\n'.join(lines) + '\n')
    for iface, (f, m, i) in counts.items():
        print(f'{iface}: {f} function pointers, {m} virtual methods, {i} inherited from CSBase')

if __name__ == '__main__':
    main()
